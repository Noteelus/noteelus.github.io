  function normalizeLang(tag) {
    if (!tag) return null;
    var n = String(tag).trim().replace(/_/g, "-").toLowerCase();
    if (n === "zh" || n === "zh-cn" || n.indexOf("zh-hans") === 0) return "zh-CN";
    if (n === "pt" || n === "pt-br" || n.indexOf("pt-br-") === 0) return "pt-BR";
    if (n === "ru" || n.indexOf("ru-") === 0) return "ru";
    if (n === "es" || n.indexOf("es-") === 0) return "es";
    if (n === "fr" || n.indexOf("fr-") === 0) return "fr";
    if (n === "tr" || n.indexOf("tr-") === 0) return "tr";
    if (n === "en" || n.indexOf("en-") === 0) return "en";
    return null;
  }

  function detectLang() {
    var q = normalizeLang(new URLSearchParams(window.location.search).get("lang"));
    if (q && dict[q]) return q;
    try {
      var saved = normalizeLang(localStorage.getItem("noteelus_lang"));
      if (saved && dict[saved]) return saved;
    } catch (_) {}
    var langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || navigator.userLanguage || "en"];
    for (var i = 0; i < langs.length; i++) {
      var m = normalizeLang(langs[i]);
      if (m && dict[m]) return m;
    }
    return "en";
  }

  function refreshLangMenu(lang) {
    var meta = langMeta[lang] || langMeta.en;
    document.querySelectorAll("[data-lang-full]").forEach(function (el) { el.textContent = meta.full; });
    document.querySelectorAll("[data-lang-short]").forEach(function (el) { el.textContent = meta.short; });
    document.querySelectorAll("[data-lang-opt]").forEach(function (opt) {
      opt.setAttribute("aria-selected", opt.getAttribute("data-lang-opt") === lang ? "true" : "false");
    });
  }

  function refreshThemeLabel(lang) {
    var d = dict[lang] || dict.en;
    var isDark = document.documentElement.getAttribute("data-theme") === "dark";
    var nextTxt = isDark ? d["theme.light"] : d["theme.dark"];
    document.querySelectorAll("[data-theme-toggle]").forEach(function (btn) {
      btn.setAttribute("aria-label", nextTxt);
      var lbl = btn.querySelector("[data-theme-label]");
      if (lbl) lbl.textContent = nextTxt;
    });
  }

  function setLang(lang, persist) {
    var norm = normalizeLang(lang) || "en";
    var l = dict[norm] ? norm : "en";
    var d = dict[l];
    document.documentElement.lang = l;
    if (persist) {
      try { localStorage.setItem("noteelus_lang", l); } catch (_) {}
    }
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      if (d[k] !== undefined) el.textContent = d[k];
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var k = el.getAttribute("data-i18n-html");
      if (d[k] !== undefined) el.innerHTML = d[k];
    });
    refreshLangMenu(l);
    refreshThemeLabel(l);
  }

  window.NoteelusI18n = { dict: dict, setLang: setLang };

  var current = detectLang();
  document.documentElement.lang = current;

  document.addEventListener("DOMContentLoaded", function () {
    setLang(current, false);

    document.querySelectorAll("[data-lang-menu]").forEach(function (menu) {
      var trigger = menu.querySelector("[data-lang-trigger]");
      var popover = menu.querySelector("[data-lang-popover]");
      if (!trigger || !popover) return;
      var opts = Array.prototype.slice.call(popover.querySelectorAll("[data-lang-opt]"));

      function closeMenu(restoreFocus) {
        if (popover.hidden) return;
        popover.hidden = true;
        trigger.setAttribute("aria-expanded", "false");
        if (restoreFocus) trigger.focus();
      }

      trigger.addEventListener("click", function (e) {
        e.stopPropagation();
        var opening = popover.hidden;
        popover.hidden = !opening;
        trigger.setAttribute("aria-expanded", opening ? "true" : "false");
      });

      opts.forEach(function (opt, idx) {
        opt.addEventListener("click", function () {
          setLang(opt.getAttribute("data-lang-opt"), true);
          closeMenu(true);
        });
        opt.addEventListener("keydown", function (e) {
          if (e.key === "ArrowDown") {
            e.preventDefault();
            opts[(idx + 1) % opts.length].focus();
          } else if (e.key === "ArrowUp") {
            e.preventDefault();
            opts[(idx - 1 + opts.length) % opts.length].focus();
          } else if (e.key === "Escape") {
            e.preventDefault();
            closeMenu(true);
          }
        });
      });

      document.addEventListener("click", function (e) {
        if (!menu.contains(e.target)) closeMenu(false);
      });
      document.addEventListener("keydown", function (e) {
        if (e.key === "Escape") closeMenu(true);
      });
    });
  });
